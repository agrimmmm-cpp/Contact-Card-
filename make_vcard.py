#!/usr/bin/env python3
"""Regenerates agrim.vcf and apps-script/Photo.gs from the details below.

Run after editing anything here:  python3 make_vcard.py
"""
import base64

CONFIG = {
    "first": "Agrim",
    "last": "Joshi",
    "title": "Computing Science Student",
    "org": "Bachelor's in Computing Science, SFU",
    "email": "aja121@sfu.ca",
    "phone": "+1-604-657-5954",  # leave "" to omit
    "linkedin": "https://www.linkedin.com/in/agrim-joshi786/",
    "portfolio": "https://agrimmmm-cpp.github.io/",
    "event": "the Tech Fair",
    "photo": "assets/photo-vcard.jpg",
}


def fold(line):
    """vCard 3.0 line folding: max 75 chars, continuation lines start with a space."""
    out, first = [], True
    while len(line) > 75:
        out.append(line[:75] if first else " " + line[:74])
        line = line[75:] if first else line[74:]
        first = False
    out.append(line if first else " " + line)
    return out


def build(c):
    b64 = base64.b64encode(open(c["photo"], "rb").read()).decode()
    lines = [
        "BEGIN:VCARD",
        "VERSION:3.0",
        f"N:{c['last']};{c['first']};;;",
        f"FN:{c['first']} {c['last']}",
        f"ORG:{c['org']}",
        f"TITLE:{c['title']}",
        f"EMAIL;TYPE=INTERNET,WORK:{c['email']}",
    ]
    if c["phone"]:
        lines.append(f"TEL;TYPE=CELL:{c['phone']}")
    lines += [
        f"URL;TYPE=LinkedIn:{c['linkedin']}",
        f"URL;TYPE=Portfolio:{c['portfolio']}",
        f"NOTE:Met at {c['event']}. Looking for software development and AI opportunities.",
        f"PHOTO;ENCODING=b;TYPE=JPEG:{b64}",
        "END:VCARD",
    ]
    folded = [seg for l in lines for seg in fold(l)]
    return "\r\n".join(folded) + "\r\n", b64


vcf, b64 = build(CONFIG)
with open("agrim.vcf", "w", newline="") as f:
    f.write(vcf)
with open("apps-script/Photo.gs", "w") as f:
    f.write("// Auto-generated by make_vcard.py. Base64 JPEG embedded in the emailed vCard.\n")
    f.write(f"const PHOTO_B64 = '{b64}';\n")
print("wrote agrim.vcf and apps-script/Photo.gs")
